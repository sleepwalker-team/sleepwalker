export const LANGUAGE_KEY = "sleepwalker.language";
let selected = "de";
try { if (globalThis.localStorage?.getItem(LANGUAGE_KEY) === "en") selected = "en"; } catch { /* Storage is optional. */ }
export const language = () => selected;
export const locale = () => selected === "en" ? "en-GB" : "de-DE";
const rendered = new Map();
export const translationFor = value => rendered.get(value);
export function renderTranslation(message) {
  const template = selected === "en" ? (english[message.key] ?? message.key) : message.key;
  return template.replace(/\$\{(\d+)\}/g, (match, index) => index < message.values.length ?
    (typeof message.values[index] === "object" && message.values[index] !== null ? renderTranslation(message.values[index]) : String(message.values[index])) : match);
}
export function t(source, ...values) {
  const key = Array.isArray(source) ? source.reduce((text, part, index) => text + (index ? "${" + (index-1) + "}" : "") + part, "") : source;
  const message = (!Array.isArray(source) && rendered.get(source)) || {key:String(key),values:values.map(value => rendered.get(value) || String(value))};
  const result = renderTranslation(message);
  rendered.set(result, message);
  if (rendered.size > 2048) rendered.delete(rendered.keys().next().value);
  return result;
}
export function applyTranslations(root = document) {
  root.documentElement?.setAttribute("lang", selected);
  for (const node of root.querySelectorAll("[data-i18n]")) {
    const key = node.dataset.i18n;
    // A dynamic value (e.g. a filename) may have replaced the initial caption.
    if ([key, english[key]].includes(node.textContent.trim())) node.textContent = t(key);
  }
  for (const attribute of ["title", "aria-label"]) {
    for (const node of root.querySelectorAll("[data-i18n-" + attribute + "]")) node.setAttribute(attribute, t(node.getAttribute("data-i18n-" + attribute)));
  }
}
export function setLanguage(value) {
  if (!["de", "en"].includes(value)) return false;
  selected = value;
  try { globalThis.localStorage?.setItem(LANGUAGE_KEY, value); } catch { /* Storage is optional. */ }
  return true;
}
